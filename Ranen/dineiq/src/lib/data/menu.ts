export const MENU: MenuItem[] = SEEDS.map(mk)

export const menuBySlug = (slug: string) => MENU.find((m) => m.slug === slug)
export const menuByCategory = (slug: string) => MENU.filter((m) => m.categorySlug === slug)
export const POPULAR_ITEMS = MENU.filter((m) => m.popular).slice(0, 8)
export const RECOMMENDED_ITEMS = MENU.filter((m) => m.recommended).slice(0, 6)
export const VEG_ITEMS = MENU.filter((m) => m.tags.includes('Vegetarian'))

export function relatedItems(slug: string, count = 4) {
  const item = menuBySlug(slug)
  if (!item) return MENU.slice(0, count)
  const sameCat = MENU.filter((m) => m.categorySlug === item.categorySlug && m.slug !== slug)
  const rest = MENU.filter((m) => m.categorySlug !== item.categorySlug)
  return [...sameCat, ...rest].slice(0, count)
}

/** Static "frequently paired" demo pairings keyed by item slug. */
export const PAIRINGS: Record<string, string[]> = {
  'maison-signature-smash': ['truffle-parmesan-fries', 'mint-lime-cooler', 'molten-lava-cake'],
  'chicken-dum-biryani': ['mango-lassi', 'chicken-tikka-boti', 'gulab-jamun-with-ice-cream'],
  'woodfired-pepperoni': ['ember-buffalo-wings', 'iced-spanish-latte', 'brownie-sundae'],
  'truffle-fettuccine-alfredo': ['stuffed-mushroom-caps', 'fresh-orange-juice', 'tiramisu-classico'],
}

export function pairedItems(slug: string) {
  const slugs = PAIRINGS[slug] ?? RECOMMENDED_ITEMS.filter((i) => i.slug !== slug).map((i) => i.slug)
  return slugs.map((s) => menuBySlug(s)).filter(Boolean) as MenuItem[]
}
